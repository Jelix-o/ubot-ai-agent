test("progress is durable, once only, scoped to owner and blocked after completion or switch-off", async (t) => {
    const f = fixture(t), contexts = new ConversationContextRepository(f.db), feedback = new RequestFeedbackService(f.repo);
    const source = f.db.insertMessage({ groupId: "10001", userId: "20001", selfId: "99999", msgId: "request", msgTime: f.base, text: "帮我整理", imagesJson: "[]", hasAtBot: true, isBotMsg: false, createdAt: f.base });
    const route = contexts.saveMessageRoute({ sourceRowId: source, groupId: "10001", userId: "20001", sourceMessageId: "request", content: "帮我整理", createdAt: f.base, routeReason: "new-topic" });
    contexts.orchestration.registerTask(route, "10001", "20001", "new");
    feedback.track(source, "conversation", f.base);
    feedback.tick(f.base + 7999);
    assert.equal(f.db.db.prepare("SELECT count(*) n FROM outbox").get()!.n, 0);
    feedback.tick(f.base + 8000);
    new RequestFeedbackService(f.repo).tick(f.base + 9000);
    const row = f.db.db.prepare("SELECT * FROM outbox WHERE kind='request_progress'").get() as unknown as OutboxRow;
    assert.ok(row);
    assert.match(feedback.validate(row, f.base + 9000), /排队/);
    assert.equal(feedback.list("10001", "20002", f.base + 9000).length, 0);
    assert.equal(feedback.list("10002", "20001", f.base + 9000).length, 0);
    assert.throws(() => feedback.validate(row, f.base + 38001), /expired/);
    contexts.orchestration.setTaskStatus(source, "running");
    assert.match(feedback.validate(row, f.base + 9000), /处理/);
    const final = f.db.enqueueOutbox("10001", null, "结果", "text", { topicId: route.topicId, branchId: route.branchId, sourceTurnId: route.turnId, turnId: 1 });
    f.db.ackOutboxDelivery(final, "final", f.base + 10000);
    let sends = 0;
    await assert.rejects(deliverOutboxRow(f.db, { async sendGroupMessage() { sends++; return { messageId: "progress" }; }, async sendGroupImage() { } }, row, f.base + 11000), /finished/);
    assert.equal(sends, 0);
    assert.equal(feedback.list("10001", "20001", f.base + 11000)[0]?.stage, "completed");
    assert.equal(feedback.list("10001", "20001", f.base + 611000).length, 0);
    f.repo.saveGroup({ ...f.repo.getGroup("10001")!, interactionAssistanceEnabled: false });
    assert.equal(feedback.list("10001", "20001").length, 0);
    assert.equal(markOutboxDeliveryFailed(f.db, row, new Error("unknown")), "terminal");
});
