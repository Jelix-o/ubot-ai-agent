    const controls = () => db.db.prepare("SELECT * FROM outbox WHERE kind='reminder_control' ORDER BY id").all() as unknown as OutboxRow[];
    const last = () => controls().at(-1)!;
    const ack = (row: OutboxRow, id = "qq-" + row.id) => { db.ackOutboxDelivery(row.id, id, base); return id; };
